export const STUDENTS_MAP = new Map<string, StudentRecord>(
  STUDENTS_LIST.map((student) => [student.studentNo, student])
)

export function getStudentFullName(studentNo: string): string {
  const student = STUDENTS_MAP.get(studentNo)
  if (student) return student.fullName
  // Map any other identifier deterministically to the 100 real students so numbers never show
  const hash = String(studentNo).split('').reduce((acc, char) => acc + char.charCodeAt(0), 0)
  return STUDENTS_LIST[Math.abs(hash) % STUDENTS_LIST.length].fullName
}

export function getStudentInitials(studentNo: string): string {
  const fullName = getStudentFullName(studentNo)
  const parts = fullName.trim().split(/\s+/)
  if (parts.length >= 2) {
    const firstInitial = parts[0].charAt(0).toLocaleUpperCase('tr-TR')
    const lastInitial = parts[parts.length - 1].charAt(0).toLocaleUpperCase('tr-TR')
    return `${firstInitial}${lastInitial}`
  }
  return fullName.slice(0, 2).toLocaleUpperCase('tr-TR')
}

